/**
 * Style Spy Web — CSS Variables & Theme Exporter
 * Generates :root CSS variables from an actual saved Design Kit plus
 * practical theme rules for body, headings, paragraphs, buttons, cards, links, and inputs.
 */
(function (global) {
  'use strict';

  function pickLuminance(hex) {
    const clean = String(hex || '').replace('#', '');
    if (clean.length !== 6) return 0.5;
    const r = parseInt(clean.slice(0, 2), 16) / 255;
    const g = parseInt(clean.slice(2, 4), 16) / 255;
    const b = parseInt(clean.slice(4, 6), 16) / 255;
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  }

  function resolveKitTokens(kit) {
    const colors = Array.isArray(kit.colors) ? kit.colors : [];
    const fonts = Array.isArray(kit.typography) ? kit.typography : [];

    // Pick smart roles from extracted colors without inventing fake data if colors exist
    const sortedByLum = colors.slice().sort((a, b) => pickLuminance(a.hex) - pickLuminance(b.hex));
    const darkest = sortedByLum[0] ? sortedByLum[0].hex : '#0F172A';
    const lightest = sortedByLum[sortedByLum.length - 1] ? sortedByLum[sortedByLum.length - 1].hex : '#F8FAFC';

    // Vibrant / non-extreme colors for primary & secondary accents
    const bgHex = colors[0] ? colors[0].hex : darkest;
    const accents = colors.filter((c) => {
      if (c.hex.toUpperCase() === bgHex.toUpperCase()) return false;
      const l = pickLuminance(c.hex);
      return l > 0.05 && l < 0.90;
    });
    const bgLum = pickLuminance(bgHex);
    const textHex = bgLum < 0.45 ? lightest : darkest;
    const primaryHex = (accents[0] && accents[0].hex) || (colors[1] && colors[1].hex) || bgHex;
    const secondaryHex = (accents[1] && accents[1].hex) || (colors[2] && colors[2].hex) || primaryHex;
    const surfaceHex = bgLum < 0.45 ? '#1E293B' : '#FFFFFF';

    const headingFont = fonts.find((f) => f.role === 'Heading') || fonts[0] || {};
    const bodyFont = fonts.find((f) => f.role === 'Body') || fonts[1] || headingFont || {};
    const buttonFont = fonts.find((f) => f.role === 'Button') || headingFont || {};

    return {
      primaryHex,
      secondaryHex,
      bgHex,
      surfaceHex,
      textHex,
      palette: colors.map((c) => c.hex),
      fontHeading: headingFont.fontFamily || 'system-ui, sans-serif',
      fontBody: bodyFont.fontFamily || 'system-ui, sans-serif',
      fontSizeHeading: headingFont.fontSize || '32px',
      fontSizeBody: bodyFont.fontSize || '16px',
      fontWeightHeading: headingFont.fontWeight || '700',
      fontWeightBody: bodyFont.fontWeight || '400',
      fontWeightButton: buttonFont.fontWeight || '600',
      lineHeightBody: bodyFont.lineHeight || '1.6'
    };
  }

  function generateCss(kit) {
    const t = resolveKitTokens(kit || {});
    const lines = [
      `/* Generated by Style Spy — Design Kit: ${(kit && kit.name) || 'Untitled Kit'} */`,
      ':root {',
      `  --color-primary: ${t.primaryHex};`,
      `  --color-secondary: ${t.secondaryHex};`,
      `  --color-background: ${t.bgHex};`,
      `  --color-surface: ${t.surfaceHex};`,
      `  --color-text: ${t.textHex};`,
      `  --font-heading: ${t.fontHeading};`,
      `  --font-body: ${t.fontBody};`,
      `  --font-size-heading: ${t.fontSizeHeading};`,
      `  --font-size-body: ${t.fontSizeBody};`,
      `  --font-weight-heading: ${t.fontWeightHeading};`,
      `  --font-weight-body: ${t.fontWeightBody};`,
      `  --font-weight-button: ${t.fontWeightButton};`,
      `  --line-height-body: ${t.lineHeightBody};`
    ];

    t.palette.forEach((hex, idx) => {
      lines.push(`  --palette-${idx + 1}: ${hex};`);
    });

    lines.push('}', '');

    // Practical theme styles using the exported CSS variables
    lines.push(
      '/* Practical Theme Styles */',
      'body {',
      '  background-color: var(--color-background);',
      '  color: var(--color-text);',
      '  font-family: var(--font-body);',
      '  font-size: var(--font-size-body);',
      '  font-weight: var(--font-weight-body);',
      '  line-height: var(--line-height-body);',
      '}',
      '',
      'h1, h2, h3, h4 {',
      '  font-family: var(--font-heading);',
      '  font-weight: var(--font-weight-heading);',
      '  color: var(--color-text);',
      '}',
      '',
      'h1 { font-size: var(--font-size-heading); }',
      '',
      'p { margin-bottom: 1rem; }',
      '',
      'a { color: var(--color-primary); text-decoration: underline; }',
      '',
      'button, .btn {',
      '  background-color: var(--color-primary);',
      '  color: #ffffff;',
      '  font-family: var(--font-heading);',
      '  font-weight: var(--font-weight-button);',
      '  border: none;',
      '  border-radius: 8px;',
      '  padding: 10px 18px;',
      '  cursor: pointer;',
      '}',
      '',
      '.card {',
      '  background-color: var(--color-surface);',
      '  border: 1px solid var(--color-secondary);',
      '  border-radius: 12px;',
      '  padding: 20px;',
      '}',
      '',
      'input, textarea, select {',
      '  background-color: var(--color-surface);',
      '  color: var(--color-text);',
      '  border: 1px solid var(--color-secondary);',
      '  border-radius: 8px;',
      '  padding: 8px 12px;',
      '  font-family: var(--font-body);',
      '}'
    );

    return lines.join('\n') + '\n';
  }

  global.StyleSpyCssExporter = {
    resolveKitTokens,
    generateCss
  };
})(typeof window !== 'undefined' ? window : globalThis);
